#!/usr/bin/env python3
"""Buy or Wait prototype.

Deterministic financial-agent engine:
- reconstructs recurring cash-flow streams from event history
- resolves blank event amounts from linked images with OCR
- applies dated FX rates
- incorporates explicit future events and message-based salary amendments
- runs a 90-day balance safety simulation
- ranks eligible payment plans and validates the final output

Run: python3 code/main.py
Optional UI: streamlit run code/app.py
"""
